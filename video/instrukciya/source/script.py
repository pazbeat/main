def normalise(s):
    for a, b in REPL:
        s = s.replace(a, b)
    import re
    out = []
    for w in re.split(r'(\W+)', s):
        out.append(STRESS.get(w, w))
    s = ''.join(out)
    s = re.sub(r'\s*,\s*,', ',', s)
    s = re.sub(r'\s+', ' ', s).strip(' ,')
    return s
